import { contextBridge, ipcRenderer } from 'electron';

contextBridge.exposeInMainWorld('electronAPI', {
  getSession: () => ipcRenderer.invoke('db/session'),
  logoutLocal: () => ipcRenderer.invoke('db/logout'),
  changePassword: (currentPassword: string, newPassword: string) => ipcRenderer.invoke('db/change-password', currentPassword, newPassword),
  saveOrder: (id: string, items: unknown[], paid: number | undefined, version: number) => ipcRenderer.invoke('db/save-order', id, items, paid, version),
  getOrder: (id: string) => ipcRenderer.invoke('db/get-order', id),
  printOrder: (id: string) => ipcRenderer.invoke('db/print-order', id),
  cancelOrder: (id: string, version: number, reason: string) => ipcRenderer.invoke('db/cancel-order', id, version, reason),
  getAdminData: () => ipcRenderer.invoke('db/admin-data'),
  getPosServerInfo: () => ipcRenderer.invoke('db/pos-server-info'),
  setDeviceActive: (id:string,active:boolean) => ipcRenderer.invoke('db/set-device-active',id,active),
  saveEntity: (entity: string, input: unknown) => ipcRenderer.invoke('db/save-entity', entity, input),
  archiveEntity: (entity: string, id: string) => ipcRenderer.invoke('db/archive-entity', entity, id),
  saveSettings: (settings: unknown) => ipcRenderer.invoke('db/save-settings', settings),
  getBackupStatus: () => ipcRenderer.invoke('db/backup-status'),
  backupNow: () => ipcRenderer.invoke('db/backup-now'),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  isDev: () => ipcRenderer.invoke('is-dev'),
  loginLocal: (username: string, password: string) => ipcRenderer.invoke('db/login', username, password),
  getSettings: () => ipcRenderer.invoke('db/get-settings'),
  getUsers: () => ipcRenderer.invoke('db/get-users'),
  getCategories: () => ipcRenderer.invoke('db/get-categories'),
  getZones: () => ipcRenderer.invoke('db/get-zones'),
  getProducts: (categoryId?: string) => ipcRenderer.invoke('db/get-products', categoryId),
  getTables: () => ipcRenderer.invoke('db/get-tables'),
  getFloor: () => ipcRenderer.invoke('db/get-floor'),
  getOrders: (status?: string, fromDate?: string, toDate?: string) => ipcRenderer.invoke('db/get-orders', status, fromDate, toDate),
  getOrderItems: (orderId: string) => ipcRenderer.invoke('db/get-order-items', orderId),
  createOrder: (order: unknown) => ipcRenderer.invoke('db/create-order', order),
});
